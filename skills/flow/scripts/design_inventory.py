GENERATED = "<!-- Generated by design_inventory.py from this project’s design records. -->"
LINK = re.compile(r"\[([^\[\]]+)\]\((<[^>]+>|[^()\s]+)\)")
ID = re.compile(r"(?<![\w-])(?:" + "|".join(IDS) + r")-\d+(?![\w-])")
KINDS = ("B", "I", "X", "E", "M", "S", "MC", "A", "L", "DC")
DETAILS = ("B", "I", "X", "E", "M", "S", "DC")
CAPACITY = ("Resource", "Interfaces", "Scenario", "Window", "Offered load",
            "Sustainable throughput", "Unit", "Utilization", "Sources", "Calculation")


def plain(text):
    return LINK.sub(r"\1", ANCHOR.sub("", text)).strip().strip("`")


def ids(text, *kinds):
    return tuple(dict.fromkeys(rid for rid in ID.findall(plain(text))
                               if not kinds or rid.split("-")[0] in kinds))


def cells(line):
    return [ANCHOR.sub("", cell).strip() for cell in re.split(r"(?<!\\)\|", line.strip().strip("|"))]


def tables(text):
    """Yield table rows with their headers and one-based source line; skip fenced examples."""
    for number, headers, values in table_rows(text):
        yield number, dict(zip(headers, values))


def col(row, name):
    return next((value for label, value in row.items() if re.match(COLUMNS[name], label)), "")


def relative_url(path, from_file, fragment=""):
    url = quote(Path(os.path.relpath(path, Path(from_file).resolve().parent)).as_posix(), safe="/")
    return url + ("#" + quote(fragment, safe="-._~") if fragment else "")


def local_link(root, document, dest, from_file):
    dest = dest.strip("<>")
    parts = urlsplit(dest)
    if parts.scheme or parts.netloc:
        return dest if parts.scheme in ("http", "https") else ""
    source = root / document
    path = source.parent / unquote(parts.path) if parts.path else source
    if not path.is_file():
        return ""
    return relative_url(path, from_file, unquote(parts.fragment))


@dataclass
class Record:
    id: str
    name: str
    document: str
    line: int
    row: dict
    anchor: str = ""
    parent: str = ""
    contract: str = ""

    @property
    def kind(self):
        return self.id.split("-")[0]

    @property
    def endpoints(self):
        return plain(col(self.row, "endpoints"))

    @property
    def participants(self):
        return ids(self.endpoints, "B")

    @property
    def resources(self):
        return ids(col(self.row, "resources") + " " + col(self.row, "limits"), "M", "A", "L")

    @property
    def protocol(self):
        value = plain(col(self.row, "protocol"))
        return "" if value in ("—", "-") else value

    @property
    def effects(self):
        return plain(col(self.row, "effects"))

    @property
    def steps(self):
        return plain(col(self.row, "steps"))

    @property
    def alternate(self):
        return plain(col(self.row, "alternate"))

    @property
    def outcome(self):
        return plain(col(self.row, "outcome"))

    @property
    def owns(self):
        return ids(col(self.row, "owns"), "E", "M")

    @property
    def faces(self):
        return ids(col(self.row, "faces"), "X")


@dataclass
class Project:
    root: Path
    records: dict = field(default_factory=dict)
    capacity: list = field(default_factory=list)
    sizing_constraints: set = field(default_factory=set)
    aspects: dict = field(default_factory=lambda: defaultdict(list))
    mechanism_details: dict = field(default_factory=dict)
    constraints_by_record: dict = field(default_factory=dict)
    part_views: dict = field(default_factory=lambda: defaultdict(list))
    context: str = ""
    architecture_file: str = ""

    def of_kind(self, *kinds):
        return [rec for rec in self.records.values() if rec.kind in kinds]

    def source_url(self, rid, from_file):
        record = self.records[rid]
        return relative_url(self.root / record.document, from_file, record.anchor)

    def linked_record(self, href, document):
        target = urlsplit(href.strip("<>"))
        rec = self.records.get(unquote(target.fragment))
        if rec and not target.netloc and not target.scheme:
            path = (document.parent / unquote(target.path)).resolve() if target.path else document
            if path == self.root / rec.document:
                return rec

    def record_mentions(self, text, document, *kinds):
        """Include descriptive Markdown links that target a published record in its owner."""
        found = list(ids(text, *kinds))
        for link in LINK.finditer(text):
            rec = self.linked_record(link[2], document)
            if rec and (not kinds or rec.kind in kinds):
                found.append(rec.id)
        return tuple(dict.fromkeys(found))


def index_constraint_references(project):
    """Join the architecture's applicability list with citations at the consuming record."""
    constraints = {rec.id: rec for rec in project.of_kind("DC")}
    if not constraints:
        return {}
    by_record = defaultdict(list)
    for constraint in constraints.values():
        document = project.root / constraint.document
        for rid in project.record_mentions(constraint.row["applies_to"], document):
            if rid in project.records and rid not in constraints:
                by_record[rid].append(constraint.id)

    for rec in project.records.values():
        if rec.kind == "DC":
            continue
        document = project.root / rec.document
        text = " ".join(rec.row.values()) + "\n" + project.mechanism_details.get(rec.id, "")
        found = list(project.record_mentions(text, document, "DC"))
        target = urlsplit(rec.contract)
        if not target.scheme and not target.netloc and target.path:
            path = (document.parent / unquote(target.path)).resolve()
            if path.is_relative_to(project.root) and path.is_file():
                found.extend(project.record_mentions(contract_reference_text(path), path, "DC"))
        for cid in found:
            if cid in constraints and cid not in by_record[rec.id]:
                by_record[rec.id].append(cid)
    return dict(by_record)


def contract_reference_text(path):
    suffix = path.suffix.lower()
    if suffix not in {".md", ".json", ".yaml", ".yml"}:
        return ""
    text = path.read_text(encoding="utf-8")
    if suffix == ".md":
        return "\n".join(line for _, line in content_lines(text.splitlines()))
    if suffix == ".json":
        def drop_comments(fields):
            fields.pop("$comment", None)
            return fields
        try:
            return json.dumps(json.loads(text, object_hook=drop_comments), ensure_ascii=False)
        except ValueError:
            return ""
    # A YAML comment starts with a separated hash outside quotes. A hash in a
    # quoted description or in a URL fragment still belongs to the spec.
    tokens = r"""'([^'\n]|'')*'|"(?:[^"\\\n]|\\.)*"|(?<!\S)\#[^\n]*"""
    return re.sub(tokens, lambda match: "" if match[0].startswith("#") else match[0], text)


def constraint_source_links(project, from_file):
    """Resolve citations beyond the browsing inventory, such as a decision or a requirement."""
    cited = {rid for constraint in project.of_kind("DC") for rid in ids(" ".join(constraint.row.values()))}
    by_owner = defaultdict(set)
    for rid in cited.difference(project.records):
        owner = IDS[rid.partition("-")[0]][0]
        by_owner[owner].add(rid)
    targets = {}
    for owner, wanted in by_owner.items():
        path = project.root / owner
        if path.is_dir() and owner == "research/":
            for rid in wanted:
                reports = list(path.glob(rid + "-*.md"))
                if len(reports) == 1:
                    targets[rid] = relative_url(reports[0], from_file)
        if not path.is_file():
            continue
        source = path.read_text(encoding="utf-8")
        lines = [line for _, line in content_lines(source.splitlines())]
        anchors = {rid for line in lines for rid in ANCHOR.findall(line)}
        declarations = {plain(values[0]) for _, _, values in table_rows(source)}
        for line in lines:
            match = re.match(r"^\s*(?:#{1,6}\s+|(?:[-*]|\d+\.)\s+\*\*)([A-Z]+-\d+)\b", line)
            if match:
                declarations.add(match[1])
        for rid in wanted.intersection(anchors | declarations):
            targets[rid] = relative_url(path, from_file, rid if rid in anchors else "")
    return targets


def read_mechanism_details(text):
    """Keep references in a detailed MC-n section separate from neighboring mechanisms."""
    sections = defaultdict(list)
    current, level = "", 0
    for language, line in blocks(text):
        if language:
            continue
        if heading := re.match(r"^(#{1,6})\s+(.*)", line):
            if len(heading[1]) <= level:
                current = ""
            if owner := re.match(r"(MC-\d+)\b", heading[2]):
                current, level = owner[1], len(heading[1])
        if current:
            sections[current].append(line)
    return {rid: "\n".join(lines) for rid, lines in sections.items()}


def read_containment(text, project):
    """Use only declared B-n nodes nested inside an explicitly identified Level 3 subgraph."""
    level, scope = 0, ""
    for language, block in blocks(text):
        if not language:
            if re.match(r"^#{1,6}\s", block):
                heading = re.search(r"(?:level|уровень)\s+([13])\b", block, re.I)
                level = int(heading[1]) if heading else 0
                scopes = ids(block, "B") if level == 3 else ()
                scope = scopes[0] if len(scopes) == 1 else ""
            continue
        if language != "mermaid":
            continue
        if level == 1 and not project.context:
            project.context = block
        if level != 3:
            continue
        if scope in project.records:
            project.part_views[scope].append(block)
        parents = []
        for raw in block.splitlines()[1:-1]:
            line = raw.strip()
            if line.startswith("subgraph "):
                labels = set(re.findall(r"\bB-?(\d+)\b", line.partition(" ")[2]))
                child = "B-" + labels.pop() if len(labels) == 1 else ""
                if child in project.records and parents and parents[-1]:
                    set_parent(project.records[child], parents[-1])
                parents.append(child if child in project.records else "")
            elif line == "end" and parents:
                parents.pop()
            elif parents and parents[-1]:
                node = re.fullmatch(r'B-?(\d+)(?:\s*\[.*\]|\s*\(.*\)|\s*\{.*\})?;?', line)
                if node and "B-" + node[1] in project.records:
                    set_parent(project.records["B-" + node[1]], parents[-1])


def set_parent(record, parent):
    if record.id != parent:
        if record.parent and record.parent != parent:
            raise ValueError(f"{record.id} has conflicting parents {record.parent} and {parent}")
        record.parent = parent


def load_project(project_dir):
    project = Project(Path(project_dir).resolve())
    if not project.root.is_dir():
        raise ValueError(f"project directory does not exist: {project.root}")
    specifications = {}
    architecture = ""
    for owner in dict.fromkeys(IDS[kind][0] for kind in KINDS):
        path = project.root / owner
        if not path.exists() and owner == "architecture.md":
            path = path.with_name("high-level-design.md")
        if not path.is_file():
            continue
        source = path.read_text(encoding="utf-8")
        anchors = {key for _, line in content_lines(source.splitlines()) for key in ANCHOR.findall(line)}
        declarations = {index + 1: (rid, name_col) for index, rid, name_col in record_rows(path.name, source)}
        if owner == "architecture.md":
            architecture = source
            project.architecture_file = path.name
        elif owner == "mechanics.md":
            project.mechanism_details = read_mechanism_details(source)
        elif owner == "data.md":
            for aspect in sorted(anchors):
                match = re.fullmatch(r"(E-\d+)-(.+)", aspect)
                if match:
                    project.aspects[match[1]].append(aspect)
        for line, row in tables(source):
            first = plain(next(iter(row.values())))
            if owner == "resource-math.md" and tuple(row) == ("input", "endpoint", "unit", "source"):
                source_link = LINK.fullmatch(row["source"])
                constraint = project.linked_record(source_link[2], path) if source_link else None
                if constraint and constraint.kind == "DC" and constraint.id == plain(row["input"]):
                    project.sizing_constraints.add(constraint.id)
                continue
            if owner == "resource-math.md" and all(key.casefold() in row for key in CAPACITY):
                project.capacity.append(row)
                continue
            spec = col(row, "spec")
            if spec and owner in ("mechanics.md", "contracts.md"):
                spec_ids = ids(first, "I") if owner == "mechanics.md" else ids(first, "X")
                target = LINK.search(spec)
                value = target[2].strip("<>") if target else plain(spec)
                if value not in ("—", "-"):
                    for rid in spec_ids:
                        specifications[rid] = value
            if not ID.fullmatch(first):
                continue
            kind = first.split("-")[0]
            if line not in declarations or first in project.records:
                continue
            _, name_col = declarations[line]
            name = plain(list(row.values())[name_col])
            if kind == "DC":
                columns = dc_columns(list(row))
                values = list(row.values())
                row = {key: values[index] for key, index in columns.items()}
            rec = Record(first, name, path.name, line, row, first if first in anchors else "")
            if kind == "B":
                parents = ids(col(row, "parent"), "B")
                if len(parents) > 1:
                    raise ValueError(f"{first} has multiple parents: {', '.join(parents)}")
                rec.parent = next(iter(parents), "")
            project.records[first] = rec
        for index, rid, title in heading_records(path.name, source):
            if rid not in project.records:
                project.records[rid] = Record(rid, plain(title) or rid, path.name, index + 1, {},
                                              rid if rid in anchors else "")
    for rid, spec in specifications.items():
        if rid in project.records:
            project.records[rid].contract = spec
    read_containment(architecture, project)
    project.constraints_by_record = index_constraint_references(project)
    return project


def access_by_part(effects):
    """Index explicit 'B-n reads E-n / updates M-n' clauses; keep the full effect text alongside."""
    read = r"reads?|looks? up|читает|считывает"
    write = (r"writes?|creates?|updates?|deletes?|stores?|appends?|enqueues?|removes?|"
             r"пишет|записывает|созда[её]т|обновляет|удаляет|добавляет")
    # Recognize only direct positive operations with explicit objects. A later
    # condition, negation or mention of another entity does not assign it a role.
    verb = f"(?:{read}|{write})"
    join = r"(?:\s*,\s*(?:(?:and|и)\s+)?|\s+(?:and|и)\s+)"
    actor = re.compile(rf"\bB-\d+(?:{join}B-\d+)*\b")
    clause = re.compile(rf"(?P<verbs>{verb}(?:\s+(?:or|and|или|и)\s+{verb})*)"
                        rf"\s+(?P<items>[EM]-\d+(?:{join}[EM]-\d+)*)\b", re.I)
    for match in actor.finditer(effects):
        owners = ids(match[0], "B")
        text = effects[match.end():]
        text = re.sub(r"^\s*(?:\([^()]*\)\s*)?[:–—-]?\s*", "", text)
        while action := clause.match(text):
            verbs = action["verbs"]
            roles = set()
            if re.search(rf"\b(?:{read})\b", verbs, re.I):
                roles.add("read")
            if re.search(rf"\b(?:{write})\b", verbs, re.I):
                roles.add("write")
            if len(roles) == 1 or not re.search(r"\b(?:or|или)\b", verbs, re.I):
                for entity in ids(action["items"]):
                    for role in sorted(roles):
                        for owner in owners:
                            yield entity, role, owner
            more = re.match(join, text[action.end():], re.I)
            if not more:
                break
            text = text[action.end() + more.end():]


def mermaid_label(text):
    # Numeric entity codes prevent display names from introducing Mermaid syntax.
    return re.sub(r'[^\w .,()/+-]', lambda m: f"#{ord(m[0])};", text)


def render_inventory(project, from_file):
    """Render a relocatable Markdown reader without modifying any source records."""
    source_links = constraint_source_links(project, from_file)

    def ref(rid, label=None):
        rec = project.records.get(rid)
        if not rec:
            return f"[{rid}]({source_links[rid]})" if rid in source_links else rid
        local = rec.kind in DETAILS or rid in project.constraints_by_record
        target = "#" + rid if local else project.source_url(rid, from_file)
        return f"[{label or rid}]({target})"

    def refs(rids):
        return ", ".join(ref(rid) for rid in dict.fromkeys(rids))

    def render_text(value, document, *, link_descriptions=False):
        # Rebase existing Markdown links before linkifying bare IDs, so links never nest.
        pieces = []
        start = 0
        for link in LINK.finditer(value):
            pieces.append(ID.sub(lambda m: ref(m[0]), value[start:link.start()]))
            record = project.linked_record(link[2], project.root / document)
            dest = urlsplit(link[2].strip("<>"))
            if record and (link_descriptions or (record.id == link[1] and dest.path in ("", record.document))):
                pieces.append(ref(record.id, link[1]))
                start = link.end()
                continue
            url = local_link(project.root, document, link[2], from_file)
            pieces.append(f"[{link[1]}]({url})" if url else link[1])
            start = link.end()
        pieces.append(ID.sub(lambda m: ref(m[0]), value[start:]))
        return "".join(pieces)

    def named(rec):
        return ref(rec.id) + " " + rec.name

    def field_line(label, value):
        return f"- **{label}** · {value or 'Unspecified'}"

    def contract_link(rec):
        if not rec.contract:
            return ""
        url = local_link(project.root, rec.document, rec.contract, from_file)
        return f"[Contract]({url})" if url else f"`{rec.contract}` (file unavailable)"

    parts = project.of_kind("B")
    exchanges = project.of_kind("I", "X")
    scenarios = project.of_kind("S")
    constraints = project.of_kind("DC")
    inventories = {"Parts": parts, "Entities": project.of_kind("E"), "Memory regions": project.of_kind("M"),
                   "Scenarios": scenarios, "Design constraints": constraints}

    part_ids = {part.id for part in parts}
    directed = [edge for interface in project.of_kind("I") for edge in directed_exchanges(interface, part_ids)]
    capacity = defaultdict(list)
    for row in project.capacity:
        capacity[row["resource"]].append(row)
    cap_links = defaultdict(list)
    cap_anchors = {}
    for number, (resource, rows) in enumerate(capacity.items(), 1):
        anchor = f"capacity-{number}"
        cap_anchors[resource] = anchor
        for rid in ids(resource + " " + " ".join(row["interfaces"] for row in rows)):
            cap_links[rid].append(f"[{plain(resource)}](#{anchor})")

    access = defaultdict(lambda: defaultdict(list))
    for rec in project.of_kind("E", "M"):
        for role, column in (("read", "readers"), ("write", "writers")):
            access[rec.id][role].extend(ids(col(rec.row, column), "B"))
    for ex in exchanges:
        for rid, role, part in access_by_part(ex.effects):
            access[rid][role].append(part)

    protocols = defaultdict(list)
    for ex in exchanges:
        protocols[ex.protocol or "Protocol unspecified"].append(ex)

    out = [GENERATED, "", f"# {project.root.name} design inventory", "", '<a id="inventory"></a>', "## Project inventory", ""]
    for title, records in inventories.items():
        if records:
            out += [field_line(title, " · ".join(map(named, records)))]
    if exchanges:
        out += ["", "### Interfaces and external boundaries by protocol", ""]
    for protocol, records in protocols.items():
        out += [field_line(protocol, " · ".join(named(r) + (f" ({contract_link(r)})" if r.contract else "")
                                             for r in records))]
    if capacity:
        out += ["", "[Capacity by resource](#capacity)"]

    if project.context:
        context_sources = [f"[Architecture]({relative_url(project.root / project.architecture_file, from_file)})"]
        context_sources.extend(map(named, project.of_kind("X")))
        out += ["", "### System context", "", project.context, "", " · ".join(context_sources)]

    if parts:
        # Mermaid uses renderer-safe node IDs. Its labels and nearby links retain the public IDs.
        out += ["", "### Parts and exchanges", "", "```mermaid", "flowchart LR"]
        for part in parts:
            label = mermaid_label(f"{part.id} {part.name}")
            out.append(f'    {part.id.replace("-", "")}["{label}"]')
        for sender, interface, receiver in directed:
            out.append(f'    {sender.replace("-", "")} -->|{interface}| {receiver.replace("-", "")}')
        out += ["```", "", " · ".join(map(named, parts + exchanges))]

    governed = [rec for rec in project.records.values()
                if rec.kind not in DETAILS and rec.id in project.constraints_by_record]
    for title, records in (("Design constraints", constraints), ("Part views", parts), ("Exchange details", exchanges),
                           ("Entities and memory regions", project.of_kind("E", "M")), ("Scenario details", scenarios),
                           ("Mechanisms and sizing records with design constraints", governed)):
        if records:
            out += ["", f"## {title}"]
        for rec in records:
            rid = rec.id
            source = project.source_url(rid, from_file)
            out += ["", f'<a id="{rid}"></a>', f"### {rid} · {rec.name}", "",
                    f"[Source record]({source}) · [Project inventory](#inventory)", ""]

            def value(name):
                return render_text(col(rec.row, name), rec.document)

            if rec.kind == "DC":
                for key, label in (("allowed_value", "Allowed value"), ("scope", "Scope"), ("basis", "Basis"),
                                   ("applies_to", "Applies to"), ("verification", "Verification")):
                    out.append(field_line(label, render_text(rec.row[key], rec.document, link_descriptions=True)))
                listed = project.record_mentions(rec.row["applies_to"], project.root / rec.document)
                other_records = [owner for owner, cids in project.constraints_by_record.items()
                                 if rid in cids and owner not in listed]
                if other_records:
                    out.append(field_line("Also cited by", refs(other_records)))
                if rid in project.sizing_constraints:
                    report = relative_url(project.root / "resource-math.md", from_file)
                    links = [f"[Resource math]({report})"]
                    for model in ("resource-math/model.py", "resource_model.py"):
                        if (project.root / model).is_file():
                            links.append(f"[Model]({relative_url(project.root / model, from_file)})")
                            break
                    out.append(field_line("Sizing calculation", " · ".join(links)))
            elif rec.kind == "B":
                related = [ex.id for ex in exchanges if rid in ex.participants or ex.id in rec.faces]
                related_data = [item for ex in exchanges if ex.id in related
                                for item in ids(ex.effects + " " + " ".join(ex.resources), "E", "M")]
                readers = [r for r, roles in access.items() if rid in roles["read"]]
                writers = [r for r, roles in access.items() if rid in roles["write"]]
                for label, content in (
                    ("Responsibility", value("meaning")), ("Parent", ref(rec.parent) if rec.parent else ""),
                    ("Contains", refs(p.id for p in parts if p.parent == rid)), ("Owns", refs(rec.owns)),
                    ("Reads", refs(readers)), ("Writes", refs(writers)),
                    ("Interfaces and boundaries", refs(related)), ("Data and memory in these exchanges", refs(related_data)),
                    ("Resources and limits", refs(rec.resources)),
                    ("Mechanisms", refs(m.id for m in project.of_kind("MC") if rid in ids(col(m.row, "B"), "B"))),
                    ("Scenarios", refs(s.id for s in scenarios
                                       if rid in ids(s.steps + " " + s.alternate) or
                                       set(related).intersection(ids(s.steps + " " + s.alternate))))):
                    if content:
                        out.append(field_line(label, content))

                for diagram in project.part_views.get(rid, ()):
                    out += ["", diagram, "", f"[{rid} source record]({source}) · [Project inventory](#inventory)"]
            elif rec.kind in ("I", "X"):
                participants = value("endpoints")
                if rec.kind == "X":
                    participants = " · ".join(filter(None, (refs(p.id for p in parts if rid in p.faces),
                                                              value("counterparty"), value("direction"))))
                for label, content in (
                    ("Participants", participants), ("Protocol", value("protocol") if rec.protocol else "Protocol unspecified"),
                    ("Entity effects", value("effects")), ("Contract", contract_link(rec))):
                    out.append(field_line(label, content))
                for label, content in (
                    ("Contract paradigm", value("paradigm")), ("Resources and limits", refs(rec.resources)),
                    ("Mechanisms", refs(mid for mid, detail in project.mechanism_details.items()
                                        if rid in ids(detail, "I", "X"))),
                    ("Scenarios", refs(s.id for s in scenarios if rid in ids(s.steps + " " + s.alternate)))):
                    if content:
                        out.append(field_line(label, content))
            elif rec.kind in ("E", "M"):
                uses = [ex.id for ex in exchanges if rid in ids(ex.effects) or rid in ex.resources]
                for label, role, key in (("Readers", "read", "readers"), ("Writers", "write", "writers")):
                    actors = list(filter(None, (value(key), refs(access[rid][role]))))
                    out.append(field_line(label, " · ".join(dict.fromkeys(actors))))
                for label, content in (
                    ("Owner", refs(p.id for p in parts if rid in p.owns)),
                    ("Meaning", value("meaning")), ("Exchanges", refs(uses)),
                    ("Resources and limits", refs(ids(" ".join(rec.row.values()), "A", "L")))):
                    if content or label == "Owner":
                        out.append(field_line(label, content))
                for aspect in project.aspects.get(rid, ()):
                    url = relative_url(project.root / rec.document, from_file, aspect)
                    out.append(f"- [State aspect · {aspect[len(rid) + 1:]}]({url})")
            elif rec.kind == "S":
                for label, key in (("Steps", "steps"), ("Alternate path", "alternate"), ("Outcome", "outcome")):
                    if value(key):
                        out.append(field_line(label, value(key)))
                main = ordered_steps(rec.steps, directed)
                alternate = ordered_steps(rec.alternate, directed) if rec.alternate else []
                if main and (alternate or not rec.alternate):
                    people = dict.fromkeys(p for a, _, b in main + alternate for p in (a, b))
                    out.extend(["", "```mermaid", "sequenceDiagram"])
                    for person in people:
                        label = mermaid_label(f"{person} {project.records[person].name}")
                        out.append(f"    participant {person.replace('-', '')} as {label}")
                    for branch, steps in (("alt Main path", main), ("else Alternate path", alternate)):
                        if alternate:
                            out.append(f"    {branch}")
                        for sender, iid, receiver in steps:
                            out.append(f"    {sender.replace('-', '')}->>{receiver.replace('-', '')}: {iid}")
                    if alternate:
                        out.append("    end")
                    out.extend(["```", "", refs(edge[1] for edge in main + alternate)])
            if rid in project.constraints_by_record:
                out.append(field_line("Design constraints", refs(project.constraints_by_record[rid])))
            if cap_links[rid]:
                out.append(field_line("Capacity", ", ".join(cap_links[rid])))

    if capacity:
        out += ["", '<a id="capacity"></a>', "## Capacity by resource", "",
                f"[Resource math]({relative_url(project.root / 'resource-math.md', from_file, 'capacity-by-resource')})"
                " · [Project inventory](#inventory)"]
    for resource, rows in capacity.items():
        out += ["", f'<a id="{cap_anchors[resource]}"></a>', "### " + plain(resource), "",
                "| " + " | ".join(CAPACITY[1:]) + " |", "|" + "---|" * (len(CAPACITY) - 1)]
        for row in rows:
            out.append("| " + " | ".join(render_text(row[key.casefold()], "resource-math.md")
                                         for key in CAPACITY[1:]) + " |")
    details = render_detail_diagrams(project.root)
    if details:
        out += ["", "## Entity and state diagrams"]
        # The helper supplies each heading and its fence together. Place source links
        # next to the corresponding diagram, including the exact authored aspect link.
        for section in re.split(r"(?m)(?=^### (?:Entity relationships|MC-\d+ state transitions)$)", details):
            if not section.strip():
                continue
            title, _, body = section.strip().partition("\n")
            links = []
            if title == "### Entity relationships":
                links.append(f"[Data model]({relative_url(project.root / 'data.md', from_file)})")
                links.extend(ref(rec.id) for rec in project.of_kind("E"))
            else:
                mid = title.split()[1]
                if mid in project.records:
                    links.append(f"[{mid} guards and effects]({project.source_url(mid, from_file)})")
                description = project.mechanism_details.get(mid, "")
                for link in LINK.finditer(description):
                    if urlsplit(link[2]).fragment in {aspect for aspects in project.aspects.values() for aspect in aspects}:
                        links.append(render_text(link[0], "mechanics.md"))
            links.append("[Project inventory](#inventory)")
            out += ["", title, "", body.strip(), "", " · ".join(dict.fromkeys(links))]
    return "\n".join(out).rstrip() + "\n"


def is_generated(path):
    if not path.is_file():
        return False
    with path.open("rb") as existing:
        return existing.readline(256).rstrip(b"\r\n") == GENERATED.encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("project_dir", type=Path)
    parser.add_argument("--output", "-o", type=Path, help="default: PROJECT/diagrams/DESIGN.md")
    args = parser.parse_args()
    try:
        project = load_project(args.project_dir)
        if not project.records:
            parser.exit(1, "No design records found in the project.\n")
        output = args.output or project.root / "diagrams" / "DESIGN.md"
        if output.is_symlink() or (output.exists() and not is_generated(output)):
            parser.error(f"output already exists and is not a generated inventory: {output}")
        markdown = render_inventory(project, output)
        output.parent.mkdir(parents=True, exist_ok=True)
        with NamedTemporaryFile(mode="w", encoding="utf-8", dir=output.parent, delete=False) as temp:
            temp_path = Path(temp.name)
            try:
                temp.write(markdown)
                temp.close()
                if not output.exists():
                    # Do not replace a file another writer created since the first check.
                    os.link(temp_path, output)
                elif not output.is_symlink() and is_generated(output):
                    os.replace(temp_path, output)
                else:
                    raise ValueError(f"output changed while generating: {output}")
            finally:
                temp_path.unlink(missing_ok=True)
        print(output)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Cannot generate design inventory: {error}\n")


if __name__ == "__main__":
    main()
