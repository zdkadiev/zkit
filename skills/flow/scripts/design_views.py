#!/usr/bin/env python3
"""Generate a local LikeC4 reader from a zkit project's Markdown records."""
import argparse
from collections import defaultdict
import json
import os
from pathlib import Path
import re
import sys
import tempfile
from urllib.parse import quote, urljoin, urlsplit

from design_inventory import ANCHOR, col, load_project, local_link, plain
from design_steps import exchanges, ordered_steps


MARKER = "// Generated by zkit design_views.py from Markdown records. Edit the source records."
INVENTORY = "diagrams/DESIGN.md"
RECORD_ID = re.compile(r"\b(?:E|M|MC|A|L)-\d+\b")


def string(value):
    """LikeC4 accepts double-quoted strings with escaped quotes and backslashes."""
    return json.dumps(" ".join(value.split()), ensure_ascii=False)


def key(record_id):
    return record_id.lower().replace("-", "")


def label(record):
    return record.id if not record.name or record.name == record.id else f"{record.id} {record.name}"


def hierarchy(parts):
    """Return LikeC4 qualified names and direct children, validating containment."""
    paths = {}
    children = defaultdict(list)

    def path(part_id, visiting):
        if part_id in visiting:
            raise ValueError("part containment cycle: " + " → ".join([*visiting, part_id]))
        if part_id not in paths:
            parent = parts[part_id].parent
            if parent and parent not in parts:
                raise ValueError(f"{part_id} has an unknown parent {parent}")
            scope = path(parent, [*visiting, part_id]) if parent else "project"
            paths[part_id] = scope + "." + key(part_id)
            children[parent or None].append(part_id)
        return paths[part_id]

    for part_id in parts:
        path(part_id, [])
    return paths, children


class DocumentLinks:
    def __init__(self, project, output, base):
        self.project = project
        self.output = output
        self.base = base.rstrip("/") + "/" if base else ""
        inventory = project.root / INVENTORY
        self.has_inventory = inventory.is_file()
        self.anchors = set(ANCHOR.findall(inventory.read_text(encoding="utf-8"))) if self.has_inventory else set()

    def url(self, target):
        parsed = urlsplit(target)
        if parsed.scheme:
            if parsed.scheme in {"http", "https"} and parsed.netloc:
                return quote(target, safe=":/#?=&%+@-._~")
            return ""
        if self.base:
            return quote(urljoin(self.base, target), safe=":/#?=&%+@-._~")
        path, fragment, anchor = target.partition("#")
        path = os.path.relpath(self.project.root / path, self.output.parent)
        if not path.startswith("."):
            path = "./" + path
        return quote(path + fragment + anchor, safe="/#%-._~")

    def source(self, record):
        return self.url(self.project.source_url(record.id, self.project.root / "index.md"))

    def record(self, record):
        urls = [(self.source(record), f"{record.id} source")]
        if record.id in self.anchors:
            urls.append((self.url(f"{INVENTORY}#{record.id}"), f"{record.id} in inventory"))
        for cid in self.project.constraints_by_record.get(record.id, ()):
            constraint = self.project.records[cid]
            url = self.url(f"{INVENTORY}#{cid}") if cid in self.anchors else self.source(constraint)
            urls.append((url, label(constraint)))
        if record.contract:
            contract = local_link(self.project.root, record.document, record.contract, self.project.root / "index.md")
            if contract:
                urls.append((self.url(contract), f"{record.id} contract"))
        return urls

    def details(self, interface):
        targets = self.record(interface)
        for record_id in dict.fromkeys([*RECORD_ID.findall(interface.effects), *interface.resources]):
            record = self.project.records.get(record_id)
            if record:
                targets.extend(self.record(record))
        return targets


def links(indent, targets):
    return [f"{indent}link {url} {string(title)}" for url, title in dict.fromkeys(targets) if url]


def project_name(project, parts):
    if parts:
        document = project.root / next(iter(parts.values())).document
        first_line = document.read_text(encoding="utf-8").lstrip().splitlines()[0]
        if first_line.startswith("# "):
            heading = re.sub(r"(?:^|\s+[–—-]\s+)(?:architecture|архитектура)$", "",
                             first_line[2:].strip(), flags=re.I)
            if heading:
                return heading
    return project.root.name


def generate(project, output, docs_base):
    parts = {part.id: part for part in project.of_kind("B")}
    boundaries = {boundary.id: boundary for boundary in project.of_kind("X")}
    if not parts and not boundaries:
        raise ValueError("no declared B-n parts or X-n boundaries to diagram")
    title = project_name(project, parts)
    docs = DocumentLinks(project, output, docs_base)
    names, children = hierarchy(parts)
    names.update({boundary: key(boundary) for boundary in boundaries})

    warnings = []
    edges = {}
    for interface in project.of_kind("I"):
        arrows = exchanges(interface, parts)
        if not arrows:
            warnings.append(f"{interface.id}: no explicit sender → recipient(s) among the declared parts")
        for arrow in arrows:
            edges[arrow] = interface

    scenarios = {}
    navigation = {}
    for scenario in project.of_kind("S"):
        for suffix, raw in [("", scenario.steps), ("_alt", scenario.alternate)]:
            if suffix and raw.strip().lower() in {"", "-", "—", "–", "none"}:
                continue
            steps = ordered_steps(raw, edges)
            if not steps:
                warnings.append(f"{scenario.id}{' alternate' if suffix else ''}: sequence omitted; "
                                "use ordered B-n → I-n → B-n steps matching declared exchanges")
                continue
            view = "scenario_" + key(scenario.id) + suffix
            scenarios[view] = (scenario, steps, bool(suffix))
            for step in steps:
                navigation.setdefault(step, view)

    # Expanding a container can hide its direct edges. A two-endpoint view keeps
    # those edges and parallel interfaces individually selectable in LikeC4.
    pairs = defaultdict(list)
    for (source, _, target), interface in edges.items():
        pairs[tuple(sorted((source, target)))].append(interface)
    pair_views = {pair: "between_" + "_".join(map(key, pair)) for pair, interfaces in pairs.items()
                  if len(interfaces) > 1 or any(children[part] for part in pair)}

    lines = [MARKER, "specification {", "  element system", "  element part",
             "  element boundary { style { color secondary } }", "  relationship exchange { multiple true }",
             "  relationship faces { head none; line dashed }", "}", "model {",
             f"  project = system {string(title)} {{"]
    if docs.has_inventory:
        lines += links("    ", [(docs.url(INVENTORY), "Design inventory")])

    def add_part(part_id, indent):
        part = parts[part_id]
        lines.append(f"{indent}{key(part.id)} = part {string(label(part))} {{")
        lines.extend(links(indent + "  ", docs.record(part)))
        for child in children[part_id]:
            add_part(child, indent + "  ")
        lines.append(indent + "}")

    for part_id in children[None]:
        add_part(part_id, "    ")
    lines.append("  }")
    for boundary in boundaries.values():
        counterparty = plain(col(boundary.row, "counterparty"))
        boundary_title = label(boundary) + (f" — {counterparty}" if counterparty else "")
        lines.append(f"  {names[boundary.id]} = boundary {string(boundary_title)} {{")
        lines += links("    ", docs.record(boundary))
        lines.append("  }")

    neighbors = defaultdict(set)
    for part in parts.values():
        for boundary in part.faces:
            if boundary in boundaries:
                neighbors[part.id].add(boundary)
                lines.append(f'  {names[part.id]} -[faces]-> {names[boundary]} "{boundary}"')
    for step, interface in edges.items():
        source, _, target = step
        neighbors[source].add(target)
        neighbors[target].add(source)
        lines.append(f"  {names[source]} -[exchange]-> {names[target]} {string(label(interface))} {{")
        pair_view = pair_views.get(tuple(sorted((source, target))))
        if pair_view:
            lines.append(f'    metadata {{ endpoints "{pair_view}" }}')
        if interface.protocol:
            lines.append(f"    technology {string(interface.protocol)}")
        if interface.effects:
            lines.append(f"    description {string(interface.effects)}")
        lines += links("    ", docs.details(interface))
        if step in navigation:
            lines.append("    navigateTo " + navigation[step])
        lines.append("  }")

    lines += ["}", "views {", "  view index {", f"    title {string(title + ' — context')}",
              "    include " + ", ".join(["project", *(names[x] for x in boundaries)]), "  }"]
    if parts:
        lines += ["  view parts of project {", '    title "Parts and boundaries"']
        if docs.has_inventory:
            lines += links("    ", [(docs.url(INVENTORY), "Design inventory")])
        lines += ["    include " + ", ".join(["project.*", *(names[x] for x in boundaries)]), "  }"]
    for part in parts.values():
        visible = {part.id, *children[part.id]}
        for member in list(visible):
            visible.update(neighbors[member])
        lines += [f"  view scope_{key(part.id)} of {names[part.id]} {{", f"    title {string(label(part))}"]
        related = [view for pair, view in pair_views.items() if part.id in pair]
        if related:
            refs = " · ".join("[[view:" + view + "]]" for view in related)
            lines.append("    description '''" + refs + "'''")
        lines += links("    ", docs.record(part))
        lines += ["    include " + ", ".join(names[x] for x in names if x in visible), "  }"]
    for (first, second), view in pair_views.items():
        lines += [f"  view {view} {{", f'    title "{first} / {second}"']
        for interface in pairs[first, second]:
            lines += links("    ", docs.record(interface))
        lines += [f"    include {names[first]}, {names[second]}",
                  f'    exclude * -> * where metadata.endpoints is not "{view}"', "  }"]
    for view, (scenario, steps, alternate) in scenarios.items():
        title = label(scenario) + (" — alternate path" if alternate else "")
        lines += [f"  dynamic view {view} {{", f"    title {string(title)}", "    variant sequence"]
        if scenario.outcome and not alternate:
            lines.append(f"    description {string(scenario.outcome)}")
        targets = docs.record(scenario)
        for interface_id in dict.fromkeys(step[1] for step in steps):
            targets.extend(docs.details(project.records[interface_id]))
        lines += links("    ", targets)
        for step in steps:
            source, _, target = step
            interface = edges[step]
            lines.append(f"    {names[source]} -> {names[target]} {string(label(interface))} {{")
            # Without an override LikeC4 inherits a sibling exchange's scenario
            # for steps sharing endpoints. The viewer suppresses self-navigation.
            lines.append("      navigateTo " + view)
            if interface.protocol:
                lines.append(f"      technology {string(interface.protocol)}")
            if interface.effects:
                lines.append(f"      notes {string(interface.effects)}")
            lines.append("    }")
        lines.append("  }")
    lines.append("}")
    return "\n".join(lines) + "\n", warnings


def write_generated(output, model):
    if output.is_symlink():
        raise ValueError(f"refusing to write to a symlink: {output}")
    existed = output.exists()
    if existed:
        with output.open(encoding="utf-8") as previous:
            if previous.readline().rstrip("\n") != MARKER:
                raise ValueError(f"output already contains an authored file: {output}")
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", dir=output.parent, delete=False, encoding="utf-8") as handle:
        temp = Path(handle.name)
        try:
            handle.write(model)
            handle.close()
            if existed:
                os.replace(temp, output)
            else:
                os.link(temp, output)  # Avoid overwriting a file created during generation.
        finally:
            temp.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("project", type=Path, help="folder containing architecture.md")
    parser.add_argument("--output", type=Path, help="generated .c4 file (default: <project>/diagrams/design.c4)")
    parser.add_argument("--docs-base", default="", help="HTTP(S) URL of the published project documentation folder")
    args = parser.parse_args()
    root = args.project.resolve()
    target = args.output or root / "diagrams/design.c4"
    output = target.parent.resolve() / target.name
    if args.docs_base:
        base = urlsplit(args.docs_base)
        if base.scheme not in {"https", "http"} or not base.netloc or base.query or base.fragment:
            parser.error("--docs-base must be an HTTP(S) project-folder URL without a query or fragment")
    try:
        if not root.is_dir():
            raise ValueError(f"project folder does not exist: {root}")
        model, warnings = generate(load_project(root), output, args.docs_base)
        write_generated(output, model)
    except (ValueError, OSError) as error:
        parser.exit(1, f"ERROR: {error}\n")
    for warning in warnings:
        print("WARN:", warning, file=sys.stderr)
    print(output)


if __name__ == "__main__":
    main()
